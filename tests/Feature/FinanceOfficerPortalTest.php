<?php

namespace Tests\Feature;

use App\Enums\BillStatus;
use App\Models\Lot;
use App\Models\Setting;
use App\Models\User;
use App\Models\UtilityBill;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Spatie\Permission\Models\Role;
use Tests\TestCase;

class FinanceOfficerPortalTest extends TestCase
{
    use RefreshDatabase;

    private User $financeOfficer;

    protected function setUp(): void
    {
        parent::setUp();

        Role::firstOrCreate(['name' => 'Finance Officer']);
        Role::firstOrCreate(['name' => 'Resident']);

        $this->financeOfficer = User::factory()->create();
        $this->financeOfficer->assignRole('Finance Officer');
    }

    public function test_finance_officer_can_view_dashboard_with_all_lots_including_multi_lot_owners(): void
    {
        $resident = User::factory()->create();
        $resident->assignRole('Resident');

        $lot1 = Lot::create(['block' => '1', 'lot_number' => '5', 'provider_managed' => false]);
        $lot2 = Lot::create(['block' => '1', 'lot_number' => '6', 'provider_managed' => false]);

        $lot1->users()->attach($resident);
        $lot2->users()->attach($resident);

        $response = $this->actingAs($this->financeOfficer)->get('/finance/dashboard');
        $response->assertStatus(200);

        $houses = $response->viewData('houses');
        $this->assertCount(2, $houses);

        $lotsFound = collect($houses)->pluck('lot')->all();
        $this->assertContains('5', $lotsFound);
        $this->assertContains('6', $lotsFound);
    }

    public function test_finance_officer_can_input_baseline_previous_reading_for_existing_resident_new_to_system(): void
    {
        $lot = Lot::create(['block' => '3', 'lot_number' => '10', 'provider_managed' => false]);
        $resident = User::factory()->create();
        $resident->assignRole('Resident');
        $lot->users()->attach($resident);

        Setting::updateOrCreate(['key' => 'elec_rate'], ['value' => 10]);

        // Cycle generated by admin with initial 0 baseline
        $bill = UtilityBill::create([
            'type' => 'electricity',
            'lot_id' => $lot->id,
            'resident_id' => $resident->id,
            'billing_period' => '2026-10-01',
            'previous_reading' => 0,
            'current_reading' => 0,
            'usage_value' => 0,
            'amount' => 0,
            'status' => BillStatus::Unpaid->value,
            'due_date' => '2026-11-15',
        ]);

        // Finance Officer inputs starting baseline: 12,450 kWh previous, 12,500 kWh current
        $res = $this->actingAs($this->financeOfficer)->postJson('/finance/api/billing/reading', [
            'type' => 'electricity',
            'block' => '3',
            'lot' => '10',
            'previous_reading' => 12450,
            'current_reading' => 12500,
            'cycle' => '2026-10',
        ]);

        $res->assertStatus(200);
        $res->assertJson([
            'success' => true,
            'bill' => [
                'previous_reading' => 12450,
                'current_reading' => 12500,
                'usage' => 50,
                'amount' => 500.0,
            ]
        ]);

        $bill->refresh();
        $this->assertEquals(12450, $bill->previous_reading);
        $this->assertEquals(12500, $bill->current_reading);
        $this->assertEquals(50, $bill->usage_value);
        $this->assertEquals(500, $bill->amount);
        $this->assertNotNull($bill->current_reading_date);
        // Due date set by Admin must be preserved!
        $this->assertEquals('2026-11-15', $bill->due_date->format('Y-m-d'));
    }

    public function test_water_bill_minimum_rate_calculation_is_accurate(): void
    {
        $lot = Lot::create(['block' => '2', 'lot_number' => '8', 'provider_managed' => false]);
        $resident = User::factory()->create();
        $resident->assignRole('Resident');
        $lot->users()->attach($resident);

        Setting::updateOrCreate(['key' => 'water_rate'], ['value' => 15]);
        Setting::updateOrCreate(['key' => 'water_min_m3'], ['value' => 10]);
        Setting::updateOrCreate(['key' => 'water_min_rate'], ['value' => 250]);

        $bill = UtilityBill::create([
            'type' => 'water',
            'lot_id' => $lot->id,
            'resident_id' => $resident->id,
            'billing_period' => '2026-10-01',
            'previous_reading' => 100,
            'current_reading' => 0,
            'usage_value' => 0,
            'amount' => 0,
            'status' => BillStatus::Unpaid->value,
            'due_date' => '2026-11-15',
        ]);

        // Case 1: Usage <= 10 m³ (e.g., 106 - 100 = 6 m³) -> Flat ₱250
        $res1 = $this->actingAs($this->financeOfficer)->postJson('/finance/api/billing/reading', [
            'type' => 'water',
            'block' => '2',
            'lot' => '8',
            'previous_reading' => 100,
            'current_reading' => 106,
            'cycle' => '2026-10',
        ]);
        $res1->assertStatus(200);
        $this->assertEquals(250, $res1->json('bill.amount'));

        // Case 2: Usage > 10 m³ (e.g., 125 - 100 = 25 m³) -> ₱250 + (15 m³ * ₱15) = ₱475
        $res2 = $this->actingAs($this->financeOfficer)->postJson('/finance/api/billing/reading', [
            'type' => 'water',
            'block' => '2',
            'lot' => '8',
            'previous_reading' => 100,
            'current_reading' => 125,
            'cycle' => '2026-10',
        ]);
        $res2->assertStatus(200);
        $this->assertEquals(475, $res2->json('bill.amount'));
    }

    public function test_paid_bills_cannot_be_modified(): void
    {
        $lot = Lot::create(['block' => '4', 'lot_number' => '1', 'provider_managed' => false]);
        $resident = User::factory()->create();
